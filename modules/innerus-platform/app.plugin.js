// InnerUs config plugin. Keeps privacy configuration reproducible across `expo prebuild --clean`.
// Android: exclude every app data domain from cloud backup AND device-to-device transfer.
// allowBackup=false alone does not cover Android 12+ device transfer (handoff A19, AC18/AC63).
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod, withEntitlementsPlist, withInfoPlist, AndroidConfig } = require('expo/config-plugins');

const DOMAINS = ['root', 'file', 'database', 'sharedpref', 'external', 'device_root', 'device_file', 'device_database', 'device_sharedpref'];
const excludes = (domains) => domains.map((domain) => `    <exclude domain="${domain}" path="." />`).join('\n');

// <data-extraction-rules> (Android 12+) does not accept the legacy device_* domains for cloud-backup in
// every OS version, so cloud-backup/device-transfer list only the documented domains.
const RULE_DOMAINS = ['root', 'file', 'database', 'sharedpref', 'external'];

const DATA_EXTRACTION_RULES = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by modules/innerus-platform/app.plugin.js. Private InnerUs data never leaves the device via backup or transfer. -->
<data-extraction-rules>
  <cloud-backup>
${excludes(RULE_DOMAINS)}
  </cloud-backup>
  <device-transfer>
${excludes(RULE_DOMAINS)}
  </device-transfer>
</data-extraction-rules>
`;

const FULL_BACKUP_CONTENT = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by modules/innerus-platform/app.plugin.js. Android 11 and lower. -->
<full-backup-content>
${excludes(DOMAINS)}
</full-backup-content>
`;

function withPrivacyBackupRules(config) {
  config = withDangerousMod(config, ['android', async (cfg) => {
    const xmlDir = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res', 'xml');
    fs.mkdirSync(xmlDir, { recursive: true });
    fs.writeFileSync(path.join(xmlDir, 'innerus_data_extraction_rules.xml'), DATA_EXTRACTION_RULES);
    fs.writeFileSync(path.join(xmlDir, 'innerus_full_backup_content.xml'), FULL_BACKUP_CONTENT);
    return cfg;
  }]);
  return withAndroidManifest(config, (cfg) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    application.$['android:allowBackup'] = 'false';
    application.$['android:dataExtractionRules'] = '@xml/innerus_data_extraction_rules';
    application.$['android:fullBackupContent'] = '@xml/innerus_full_backup_content';
    return cfg;
  });
}

// iOS private iCloud sync (spec 32-36). On by default; opt out with INNERUS_CLOUDKIT=0 at prebuild time
// (the app then runs local-only and shows "iCloud is unavailable"). Defaults to the development container and
// environment; only the production variant (app.config.js, APP_VARIANT=production) passes the live container
// `iCloud.com.nicksmet.innerus` with environment Production (decision D27). No push entitlement (aps-environment):
// the app pulls changes at launch and when it returns to the foreground instead of using silent pushes.
const DEVELOPMENT_CLOUDKIT = { container: 'iCloud.local.innerus.development', environment: 'Development' };
function cloudKitEnabled() {
  return process.env.INNERUS_CLOUDKIT !== '0';
}
function withCloudKitSync(config, { container, environment }) {
  if (!cloudKitEnabled()) return config;
  config = withEntitlementsPlist(config, (cfg) => {
    cfg.modResults['com.apple.developer.icloud-services'] = ['CloudKit'];
    cfg.modResults['com.apple.developer.icloud-container-identifiers'] = [container];
    cfg.modResults['com.apple.developer.icloud-container-environment'] = environment;
    return cfg;
  });
  // Marker read by the Swift adapter: it never constructs a CKContainer without it (an unentitled
  // container identifier would crash the app).
  return withInfoPlist(config, (cfg) => {
    cfg.modResults.InnerUsCloudKitContainer = container;
    return cfg;
  });
}

module.exports = function withInnerUsPlatform(config, props = {}) {
  const cloudKit = {
    container: props.cloudKitContainer ?? DEVELOPMENT_CLOUDKIT.container,
    environment: props.cloudKitEnvironment ?? DEVELOPMENT_CLOUDKIT.environment,
  };
  return withCloudKitSync(withPrivacyBackupRules(config), cloudKit);
};
